function renderStats(){const ps=pets(),ownedIds=Object.keys(state.owned).filter(id=>state.owned[id]>0),income=ps.reduce((s,p)=>s+(state.owned[p.id]||0)*p.income,0);const rare=ps.filter(p=>state.owned[p.id]).sort((a,b)=>RARITIES.indexOf(b.rarity)-RARITIES.indexOf(a.rarity))[0];document.querySelector('#statsGrid').innerHTML=[['💎',`${ownedIds.length}/${ps.length}`,'Gesammelte Tiere'],['💰',`$${fmt(income)}/s`,'Gesamteinkommen'],['⭐',state.favorites.length,'Favoriten'],['👑',rare?.name||'Noch keines','Seltenstes Tier']].map(x=>`<div class="stat-card glass"><div class="stat-icon">${x[0]}</div><div><b>${x[1]}</b><small>${x[2]}</small></div></div>`).join('')}
function renderDashboard(){const ps=pets();document.querySelector('#biomeProgress').innerHTML=Object.keys(BIOMES).slice(0,5).map(b=>{const all=ps.filter(p=>p.biome===b),got=all.filter(p=>state.owned[p.id]).length;return `<div class="progress-row"><div class="progress-label"><span>${BIOMES[b][0]} ${b}</span><b>${got}/${all.length}</b></div><div class="progress"><span style="width:${pct(got,all.length)}%"></span></div></div>`}).join('');const p=ps[new Date().getDate()%ps.length];document.querySelector('#dailyPet').innerHTML=`<div class="daily"><div class="daily-icon">${p.icon}</div><div><span class="rarity" style="color:${COLORS[p.rarity]}">${p.rarity}</span><h2>${p.name}</h2><p class="pet-income">+$${fmt(p.income)}/s</p><button class="secondary" data-open="${p.id}">Ansehen</button></div></div>`}
function renderDex(){let list=pets();const q=document.querySelector('#dexSearch').value.toLowerCase(),r=document.querySelector('#rarityFilter').value,b=document.querySelector('#biomeFilter').value,s=document.querySelector('#sortFilter').value;list=list.filter(p=>p.name.toLowerCase().includes(q)&&(r==='all'||p.rarity===r)&&(b==='all'||p.biome===b)&&(!onlyMissing||!state.owned[p.id]));list.sort((a,b)=>s==='income'?b.income-a.income:s==='name'?a.name.localeCompare(b.name):RARITIES.indexOf(b.rarity)-RARITIES.indexOf(a.rarity));document.querySelector('#dexCount').textContent=pets().length;document.querySelector('#petGrid').innerHTML=list.map(petCard).join('')||'<div class="empty">Keine Tiere gefunden.</div>'}
function renderCollection(){const ps=pets();let list=ps.filter(p=>state.owned[p.id]);if(currentCollection==='favorites')list=ps.filter(p=>state.favorites.includes(p.id));if(currentCollection==='duplicates')list=ps.filter(p=>(state.owned[p.id]||0)>1);const income=ps.reduce((s,p)=>s+(state.owned[p.id]||0)*p.income,0),count=ps.filter(p=>state.owned[p.id]).length;document.querySelector('#collectionSummary').innerHTML=`<div class="big-progress" style="--pct:${pct(count,ps.length)}%"><b>${pct(count,ps.length)}%</b></div><div class="summary-data"><div><b>${count}/${ps.length}</b><small>Einträge</small></div><div><b>$${fmt(income)}/s</b><small>Einkommen</small></div><div><b>${Object.values(state.owned).reduce((a,b)=>a+b,0)}</b><small>Tiere gesamt</small></div></div>`;document.querySelector('#collectionGrid').innerHTML=list.map(petCard).join('')||'<div class="empty">Hier ist es noch leer. Öffne den EggDex und sammle dein erstes Tier!</div>'}
function renderBiomes(){const ps=pets();document.querySelector('#biomeGrid').innerHTML=Object.entries(BIOMES).map(([b,[icon,color]])=>{const all=ps.filter(p=>p.biome===b),got=all.filter(p=>state.owned[p.id]).length;return `<article class="biome-card" style="--biome:${color}"><span class="biome-emoji">${icon}</span><span class="eyebrow">BIOM</span><h2>${b}</h2><p>${got} von ${all.length} Tieren gesammelt</p><div class="progress"><span style="width:${pct(got,all.length)}%"></span></div><p><b>${pct(got,all.length)}%</b> abgeschlossen</p></article>`}).join('')}
function renderCalc(){const ps=pets().filter(p=>state.owned[p.id]);document.querySelector('#calcList').innerHTML=ps.length?ps.map(p=>`<div class="calc-row"><span>${p.icon}</span><div><b>${p.name}</b><small class="pet-income"> $${fmt(p.income)}/s</small></div><input class="calc-qty" data-id="${p.id}" type="number" value="${state.owned[p.id]}" min="0"></div>`).join(''):'<div class="empty">Sammle zuerst Tiere im EggDex.</div>';calcResults()}
function calcResults(){const selected=[...document.querySelectorAll('.calc-qty')].map(i=>({p:pets().find(p=>p.id===i.dataset.id),q:+i.value||0})).filter(x=>x.p&&x.q);const total=selected.reduce((s,x)=>s+x.p.income*x.q,0);const top=selected.sort((a,b)=>b.p.income*b.q-a.p.income*a.q).slice(0,5);document.querySelector('#calcResults').innerHTML=`<span class="eyebrow">DEIN ERGEBNIS</span><h2>Gesamteinkommen</h2><div class="money-total">$${fmt(total)}/s</div><div class="result-stack"><div class="result-line"><span>Pro Minute</span><b>$${fmt(total*60)}</b></div><div class="result-line"><span>Pro Stunde</span><b>$${fmt(total*3600)}</b></div><div class="result-line"><span>In 24 Stunden</span><b>$${fmt(total*86400)}</b></div></div><div class="bar-chart">${top.map(x=>`<div style="height:${total?Math.max(6,x.p.income*x.q/Math.max(...top.map(t=>t.p.income*t.q))*100):0}%"><small>${x.p.icon} ${x.p.name}</small></div>`).join('')}</div>`}
